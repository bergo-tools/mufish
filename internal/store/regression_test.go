// setMoveBizDate 修改库存流水的业务日期，用于验证按日期区间统计的报表。
func setMoveBizDate(t *testing.T, st *Store, bizType string, bizID int64, at string) {
	t.Helper()
	if _, err := st.DB().Exec(
		`UPDATE stock_moves SET biz_date=? WHERE biz_type=? AND biz_id=?`,
		at, bizType, bizID); err != nil {
		t.Fatalf("修改库存流水业务日期失败: %v", err)
	}
}

// 自动编码不能阻塞：SQLite 单连接下，打开 Rows 后继续查询会等待连接。
func TestAutoGeneratedCodesDoNotBlock(t *testing.T) {
	st := newTestStore(t)
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	pid, err := st.SaveProduct(ctx, 0, ProductInput{Name: "自动编码商品", Unit: "个", Status: 1})
	if err != nil {
		t.Fatalf("自动生成商品编码失败（可能发生连接阻塞）: %v", err)
	}
	p, err := st.GetProduct(ctx, pid)
	if err != nil {
		t.Fatalf("读取商品失败: %v", err)
	}
	if !strings.HasPrefix(p.Code, "SP") {
		t.Fatalf("商品编码应以 SP 开头，实际 %q", p.Code)
	}

	cid, err := st.SavePartner(ctx, 0, PartnerInput{Name: "自动编码客户", Type: "customer", Status: 1})
	if err != nil {
		t.Fatalf("自动生成客户编码失败（可能发生连接阻塞）: %v", err)
	}
	c, err := st.GetPartner(ctx, cid)
	if err != nil {
		t.Fatalf("读取客户失败: %v", err)
	}
	if !strings.HasPrefix(c.Code, "KH") {
		t.Fatalf("客户编码应以 KH 开头，实际 %q", c.Code)
	}

	sid, err := st.SavePartner(ctx, 0, PartnerInput{Name: "自动编码供应商", Type: "supplier", Status: 1})
	if err != nil {
		t.Fatalf("自动生成供应商编码失败: %v", err)
	}
	s, err := st.GetPartner(ctx, sid)
	if err != nil {
		t.Fatalf("读取供应商失败: %v", err)
	}
	if !strings.HasPrefix(s.Code, "GYS") {
		t.Fatalf("供应商编码应以 GYS 开头，实际 %q", s.Code)
	}

	wid, err := st.SaveWarehouse(ctx, 0, WarehouseInput{Name: "自动编码仓库", Status: 1})
	if err != nil {
		t.Fatalf("自动生成仓库编码失败: %v", err)
	}
	w, err := st.GetWarehouse(ctx, wid)
	if err != nil {
		t.Fatalf("读取仓库失败: %v", err)
	}
	if !strings.HasPrefix(w.Code, "WH") {
		t.Fatalf("仓库编码应以 WH 开头，实际 %q", w.Code)
	}

	aid, err := st.SaveAccount(ctx, 0, AccountInput{Name: "自动编码账户", Type: "cash", Status: 1})
	if err != nil {
		t.Fatalf("自动生成账户编码失败: %v", err)
	}
	a, err := st.GetAccount(ctx, aid)
	if err != nil {
		t.Fatalf("读取账户失败: %v", err)
	}
	if !strings.HasPrefix(a.Code, "ACC") {
		t.Fatalf("账户编码应以 ACC 开头，实际 %q", a.Code)
	}
}

